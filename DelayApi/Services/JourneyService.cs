using Microsoft.Playwright;

namespace DelayApi.Services
{


    public class JourneyService
    {
        private readonly IPlaywright _playwright;
        private readonly IBrowser _browser;

        //private readonly websiteBaseUrl = "https://www.skanetrafiken.se/"

        public JourneyService()
        {
            _playwright = Playwright.CreateAsync()
                .GetAwaiter()
                .GetResult();

            _browser = _playwright.Chromium.LaunchAsync(
                new BrowserTypeLaunchOptions
                {
                    Headless = true
                })
                .GetAwaiter()
                .GetResult();
        }

        public async Task<string> SearchAsync(
            string from,
            string to,
            string date)
        {
            var context = await _browser.NewContextAsync();

            var page = await context.NewPageAsync();

            try
            {
                await page.GotoAsync(
                    "https://example.com/",
                    new PageGotoOptions
                    {
                        WaitUntil = WaitUntilState.NetworkIdle
                    });

                // Fill/select the website's inputs
                await page.SelectOptionAsync(
                    "#from",
                    from);

                await page.SelectOptionAsync(
                    "#to",
                    to);

                await page.FillAsync(
                    "#date",
                    date);

                // Wait for the internal API request
                var responseTask =
                    page.WaitForResponseAsync(response =>
                        response.Url.Contains("/api/search"));

                // Trigger the website's search
                await page.ClickAsync("#search");

                // Get the response generated by the website
                var response = await responseTask;

                if (!response.Ok)
                {
                    throw new Exception(
                        $"Target website returned {response.Status}");
                }

                return await response.TextAsync();
            }
            finally
            {
                await context.CloseAsync();
            }
        }
    }
}
